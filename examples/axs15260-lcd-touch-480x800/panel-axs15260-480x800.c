static int axs15260_prepare(struct drm_panel *panel)
{
	struct axs15260 *axs15260 = to_axs15260(panel);
	struct mipi_dsi_multi_context ctx = { .dsi = axs15260->dsi };

	if (axs15260->reset) {
		gpiod_set_value_cansleep(axs15260->reset, 1);
		msleep(axs15260->desc->pwr_timing->post_reset);
		gpiod_set_value_cansleep(axs15260->reset, 0);
		msleep(axs15260->desc->pwr_timing->reset_low);
		gpiod_set_value_cansleep(axs15260->reset, 1);
		msleep(axs15260->desc->pwr_timing->after_reset);
	}

	if (axs15260->desc->do_sw_reset) {
		mipi_dsi_dcs_soft_reset_multi(&ctx);
		msleep(axs15260->desc->pwr_timing->after_reset);
	}

	if (axs15260->desc->init_sequence) {
		int ret = axs15260->desc->init_sequence(axs15260->dsi);
		if (ret)
			return ret;
	}

	return ctx.accum_err;
}

static int axs15260_enable(struct drm_panel *panel)
{
	struct mipi_dsi_multi_context ctx = { .dsi = to_mipi_dsi_device(panel->dev) };
	mipi_dsi_dcs_set_display_on_multi(&ctx);
	return ctx.accum_err;
}

static int axs15260_disable(struct drm_panel *panel)
{
	struct mipi_dsi_multi_context ctx = { .dsi = to_mipi_dsi_device(panel->dev) };
	mipi_dsi_dcs_set_display_off_multi(&ctx);
	return ctx.accum_err;
}

static int axs15260_unprepare(struct drm_panel *panel)
{
	struct axs15260 *axs15260 = to_axs15260(panel);
	struct mipi_dsi_multi_context ctx = { .dsi = axs15260->dsi };

	mipi_dsi_dcs_enter_sleep_mode_multi(&ctx);
	if (axs15260->reset)
		gpiod_set_value_cansleep(axs15260->reset, 0);

	return ctx.accum_err;
}

static int axs15260_get_modes(struct drm_panel *panel, struct drm_connector *connector)
{
	struct axs15260 *axs15260 = to_axs15260(panel);
	struct drm_display_mode *mode;

	mode = drm_mode_duplicate(connector->dev, axs15260->desc->mode);
	if (!mode)
		return -ENOMEM;

	drm_mode_set_name(mode);
	drm_mode_probed_add(connector, mode);

	connector->display_info.width_mm = mode->width_mm;
	connector->display_info.height_mm = mode->height_mm;

	drm_connector_set_orientation_from_panel(connector, panel);
	return 1;
}

static enum drm_panel_orientation axs15260_get_orientation(struct drm_panel *panel)
{
	return to_axs15260(panel)->orientation;
}

static const struct drm_panel_funcs axs15260_funcs = {
	.prepare = axs15260_prepare,
	.enable = axs15260_enable,
	.disable = axs15260_disable,
	.unprepare = axs15260_unprepare,
	.get_modes = axs15260_get_modes,
	.get_orientation = axs15260_get_orientation,
};

/* ==================== 3.97寸 480x800 DPI 时序与物理尺寸配置 ==================== */
static const struct drm_display_mode axs15260_mode = {
	/* 35.7 MHz Pixel Clock */
	.clock = 35700,

	/* 水平时序 (Horizontal Timing) */
	.hdisplay = 480,
	.hsync_start = 480 + 70,		/* HFP: 70 */
	.hsync_end   = 480 + 70 + 10,		/* HSW: 10 */
	.htotal      = 480 + 70 + 10 + 70,	/* HBP: 70 (HTOTAL = 630) */

	/* 垂直时序 (Vertical Timing) */
	.vdisplay = 800,
	.vsync_start = 800 + 125,		/* VFP: 125 */
	.vsync_end   = 800 + 125 + 2,		/* VSW: 2 */
	.vtotal      = 800 + 125 + 2 + 20,	/* VBP: 20 (VTOTAL = 947) */

	/* 3.97 寸 480x800 屏幕标准显示区域物理尺寸 (单位: mm) */
	.width_mm = 52,
	.height_mm = 86,

	.type = DRM_MODE_TYPE_DRIVER | DRM_MODE_TYPE_PREFERRED,
};

static const struct power_on_timing axs15260_pwr_timing = {
	.post_reset = 10,
	.reset_low = 10,
	.after_reset = 50,
	.slpout = 120,
};

static const struct axs15260_desc axs15260_desc = {
	.mode = &axs15260_mode,
	.lanes = 2, /* AXS15260 MIPI-DSI 为 2 Lane */
	.flags = MIPI_DSI_MODE_VIDEO | MIPI_DSI_MODE_VIDEO_BURST | MIPI_DSI_MODE_LPM,
	.format = MIPI_DSI_FMT_RGB888,
	.init_sequence = axs15260_480x800_init_sequence,
	.pwr_timing = &axs15260_pwr_timing,
	.do_sw_reset = false,
};

static int axs15260_probe(struct mipi_dsi_device *dsi)
{
	struct axs15260 *axs15260;
	const struct axs15260_desc *desc;
	int ret;

	axs15260 = devm_kzalloc(&dsi->dev, sizeof(*axs15260), GFP_KERNEL);
	if (!axs15260)
		return -ENOMEM;

	desc = of_device_get_match_data(&dsi->dev);
	dsi->mode_flags = desc->flags;
	dsi->format = desc->format;
	dsi->lanes = desc->lanes;

	axs15260->panel.prepare_prev_first = true;
	axs15260->reset = devm_gpiod_get_optional(&dsi->dev, "reset", GPIOD_OUT_HIGH);
	if (IS_ERR(axs15260->reset)) {
		dev_err(&dsi->dev, "Failed to get reset GPIO\n");
		return PTR_ERR(axs15260->reset);
	}

	ret = of_drm_get_panel_orientation(dsi->dev.of_node, &axs15260->orientation);
	if (ret < 0)
		axs15260->orientation = DRM_MODE_PANEL_ORIENTATION_NORMAL;

	drm_panel_init(&axs15260->panel, &dsi->dev, &axs15260_funcs, DRM_MODE_CONNECTOR_DSI);

	ret = drm_panel_of_backlight(&axs15260->panel);
	if (ret)
		return ret;

	drm_panel_add(&axs15260->panel);

	mipi_dsi_set_drvdata(dsi, axs15260);
	axs15260->dsi = dsi;
	axs15260->desc = desc;

	ret = mipi_dsi_attach(dsi);
	if (ret)
		drm_panel_remove(&axs15260->panel);

	return ret;
}

static void axs15260_remove(struct mipi_dsi_device *dsi)
{
	struct axs15260 *axs15260 = mipi_dsi_get_drvdata(dsi);

	mipi_dsi_detach(dsi);
	drm_panel_remove(&axs15260->panel);
}

static const struct of_device_id axs15260_of_match[] = {
	{ .compatible = "axs,axs15260-480x800", .data = &axs15260_desc },
	{ }
};
MODULE_DEVICE_TABLE(of, axs15260_of_match);

static struct mipi_dsi_driver axs15260_driver = {
	.probe = axs15260_probe,
	.remove = axs15260_remove,
	.driver = {
		.name = "panel-axs15260-480x800",
		.of_match_table = axs15260_of_match,
	},
};
module_mipi_dsi_driver(axs15260_driver);

